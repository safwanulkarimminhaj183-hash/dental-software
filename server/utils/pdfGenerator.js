import PDFDocument from 'pdfkit';

/**
 * Generate Professional Digital Prescription PDF Buffer using PDFKit
 */
export const generatePrescriptionPDF = (rx) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: 'A4', margin: 40 });
      const buffers = [];

      doc.on('data', (chunk) => buffers.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', (err) => reject(err));

      // ─── Header ─────────────────────────────────────────────────────────────
      doc.fillColor('#0e2a47').fontSize(22).font('Helvetica-Bold').text('DentoCare Clinic', 40, 40);
      doc.fontSize(10).font('Helvetica').fillColor('#3ec1d3').text('Specialist Oral Healthcare & Digital Dentistry', 40, 65);
      doc.fontSize(9).fillColor('#64748b').text('512-205-1826 | notifications@dentocare.clinic | Jalalabad, Sylhet', 40, 78);

      doc.moveTo(40, 95).lineTo(550, 95).strokeColor('#e2e8f0').lineWidth(1).stroke();

      // ─── Doctor & Prescription Details ────────────────────────────────────
      doc.fontSize(12).font('Helvetica-Bold').fillColor('#0e2a47').text(rx.doctorName || 'Dr. Sarah Johnson', 40, 110);
      doc.fontSize(9).font('Helvetica').fillColor('#64748b').text(`License: ${rx.doctorLicense || 'DC-LICENSE-98412'}`, 40, 125);

      doc.fontSize(10).font('Helvetica-Bold').fillColor('#0e2a47').text(`Prescription No: ${rx.prescriptionNumber || 'RX-000000'}`, 380, 110, { align: 'right' });
      doc.fontSize(9).font('Helvetica').fillColor('#64748b').text(`Date: ${new Date(rx.createdAt || Date.now()).toDateString()}`, 380, 125, { align: 'right' });

      doc.moveTo(40, 145).lineTo(550, 145).strokeColor('#e2e8f0').stroke();

      // ─── Patient Profile Box ──────────────────────────────────────────────
      doc.rect(40, 155, 510, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#0e2a47').fontSize(10).font('Helvetica-Bold').text(`Patient Name: `, 50, 165, { continued: true });
      doc.font('Helvetica').text(`${rx.patientName} (${rx.patientAge || 30} yrs)`);
      doc.font('Helvetica-Bold').text(`Email: `, 50, 180, { continued: true });
      doc.font('Helvetica').text(`${rx.patientEmail}`);

      doc.fontSize(10).font('Helvetica-Bold').text(`Diagnosis: `, 300, 165, { continued: true });
      doc.font('Helvetica').fillColor('#dc2626').text(`${rx.diagnosis}`);

      // ─── Medications Table ────────────────────────────────────────────────
      doc.fontSize(14).font('Helvetica-Bold').fillColor('#0e2a47').text('Rx Medications', 40, 215);

      // Table Header
      let y = 235;
      doc.rect(40, y, 510, 22).fill('#3ec1d3');
      doc.fillColor('#ffffff').fontSize(9).font('Helvetica-Bold');
      doc.text('Medication Name', 50, y + 6);
      doc.text('Dosage', 200, y + 6);
      doc.text('Frequency', 280, y + 6);
      doc.text('Duration', 400, y + 6);
      doc.text('Instructions', 470, y + 6);

      y += 22;
      doc.font('Helvetica').fontSize(9).fillColor('#1e293b');

      if (rx.medications && rx.medications.length > 0) {
        rx.medications.forEach((med, idx) => {
          const bgColor = idx % 2 === 0 ? '#ffffff' : '#f8fafc';
          doc.rect(40, y, 510, 25).fillAndStroke(bgColor, '#f1f5f9');
          doc.fillColor('#1e293b');
          doc.text(med.name, 50, y + 7);
          doc.text(med.dosage, 200, y + 7);
          doc.text(med.frequency, 280, y + 7);
          doc.text(med.duration, 400, y + 7);
          doc.text(med.instructions || '-', 470, y + 7);
          y += 25;
        });
      } else {
        doc.rect(40, y, 510, 25).fill('#ffffff');
        doc.text('No specific medications assigned.', 50, y + 7);
        y += 25;
      }

      // ─── Advice & Follow-Up ────────────────────────────────────────────────
      y += 20;
      doc.fontSize(11).font('Helvetica-Bold').fillColor('#0e2a47').text('Clinical Advice & Instructions:', 40, y);
      y += 15;
      doc.fontSize(9).font('Helvetica').fillColor('#475569').text(rx.generalAdvice || 'Maintain regular oral hygiene. Follow post-op guidance.', 40, y, { width: 510 });

      if (rx.nextFollowUpDate) {
        y += 35;
        doc.fontSize(10).font('Helvetica-Bold').fillColor('#3ec1d3').text(`Next Scheduled Follow-up: ${new Date(rx.nextFollowUpDate).toDateString()}`, 40, y);
      }

      // ─── Footer Stamp ──────────────────────────────────────────────────────
      doc.fontSize(8).fillColor('#94a3b8').text('This is a verified digital prescription generated by DentoCare Clinical System.', 40, 750, { align: 'center' });

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
};
